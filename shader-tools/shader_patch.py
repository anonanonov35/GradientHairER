"""Add a model-space hair gradient to the user's DXIL programs.

Only transformations are distributed. The original shader remains private.
"""
import re
import struct
import subprocess
from environment import WORKSPACE, LAB, DXC_DIR
from dxil import assemble

DXC=DXC_DIR/'dxc.exe'

def disassemble(raw,stem):
    cache=LAB/'dxil'
    cache.mkdir(exist_ok=True)
    source=cache/(stem+'.dxil')
    dest=cache/(stem+'.ll')
    source.write_bytes(raw)
    subprocess.run([str(DXC),'-dumpbin',str(source),'-Fc',str(dest)],check=True,capture_output=True)
    return dest.read_text(encoding='utf-8')

def metadata(text):
    return {int(m[1]):m[2] for m in re.finditer(r'^!(\d+) = (.*)$',text,re.M)}

def add_varying(text,vertex):
    md=metadata(text)
    entry=int(re.search(r'!dx.entryPoints = !\{!(\d+)\}',text)[1])
    sig=int(re.search(r'!"[^"\n]+", !(\d+),',md[entry])[1])
    lists=re.findall(r'!(\d+)|null',md[sig])
    list_id=int(lists[1 if vertex else 0])
    members=[int(x) for x in re.findall(r'!(\d+)',md[list_id])]
    # Use the same free semantic/register in every pass.
    slots=[]
    for n in members:
        slots.append(int(re.search(r'i8 \d+, i32 (\d+), i8 \d+, (?:null|!\d+)\}',md[n])[1]))
    register=12
    assert max(slots)<register,slots
    next_id=max(md)+1
    semantic_id=max(int(re.search(r'i32 (\d+),',md[n])[1]) for n in members)+1
    row=f'!{{i32 {semantic_id}, !"TEXCOORD", i8 9, i8 0, !{next_id+1}, i8 2, i32 1, i8 1, i32 {register}, i8 0, !{next_id+2}}}'
    text=text.replace(f'!{list_id} = {md[list_id]}',f'!{list_id} = {md[list_id][:-1]}, !{next_id}}}')
    text += f'\n!{next_id} = {row}\n!{next_id+1} = !{{i32 15}}\n!{next_id+2} = !{{i32 3, i32 1}}\n'
    # The dependency mask is regenerated by the assembler/validator below.
    text=re.sub(r'^!dx.viewIdState = .*\n','',text,flags=re.M)
    return text,semantic_id

def patch_vertex(text):
    if '!"TEXCOORD"' not in text or 'i32 5, i32 5, i32 0' not in text:return None
    text,sig=add_varying(text,True)
    md=metadata(text)
    pos=next(int(re.search(r'i32 (\d+),',row)[1]) for row in md.values()
        if '!"POSITION"' in row and 'i8 0, i32 1, i8 3' in row)
    body=(f'  %hgY = call float @dx.op.loadInput.f32(i32 4, i32 {pos}, i32 0, i8 1, i32 undef)\n'
          f'  call void @dx.op.storeOutput.f32(i32 5, i32 {sig}, i32 0, i8 0, float %hgY)\n')
    text=text.replace('  ret void',body+'  ret void')
    return text

def patch_pixel(text):
    # Identify material CB (b3), never scene/instance CBs at the same register.
    h=re.search(r'(%\d+) = call %dx.types.Handle @dx.op.createHandle\(i32 57, i8 2, i32 \d+, i32 3, i1 false\)',text)
    if not h:return None
    handle=h[1]
    load=re.search(r'(%\d+) = call %dx.types.CBufRet.f32 @dx.op.cbufferLoadLegacy.f32\(i32 59, %dx.types.Handle '+re.escape(handle)+r', i32 10\)',text)
    if not load:return None
    color=load[1]
    channels=[]
    ends=[]
    for c in range(3):
        match=re.search(r'(%\d+) = extractvalue %dx.types.CBufRet.f32 '+re.escape(color)+f', {c}[^\n]*\n',text)
        if not match:return None
        channels.append(match[1]);ends.append(match.end())
    text,sig=add_varying(text,False)
    at=max(ends)
    # Bounds: 10-bit model-space Y endpoints in [-1, 3] meters.
    # Controls: exact 16-bit payload plus presence bit in secondary alpha.
    code=f'''  %hgBoundsF = extractvalue %dx.types.CBufRet.f32 {color}, 3
  %hgBoundsU = fptoui float %hgBoundsF to i32
  %hgMinU = and i32 %hgBoundsU, 1023
  %hgMaxShift = lshr i32 %hgBoundsU, 10
  %hgMaxU = and i32 %hgMaxShift, 1023
  %hgMinF = uitofp i32 %hgMinU to float
  %hgMaxF = uitofp i32 %hgMaxU to float
  %hgMinScale = fmul float %hgMinF, 0x3F70040100000000
  %hgMaxScale = fmul float %hgMaxF, 0x3F70040100000000
  %hgMin = fsub float %hgMinScale, 1.000000e+00
  %hgMax = fsub float %hgMaxScale, 1.000000e+00
  %hgSpan0 = fsub float %hgMax, %hgMin
  %hgSpan = call float @dx.op.binary.f32(i32 35, float %hgSpan0, float 0x3F847AE140000000)
  %hgY = call float @dx.op.loadInput.f32(i32 4, i32 {sig}, i32 0, i8 0, i32 undef)
  %hgDistance = fsub float %hgMax, %hgY
  %hgHeight = fdiv float %hgDistance, %hgSpan
  %hgSecond = call %dx.types.CBufRet.f32 @dx.op.cbufferLoadLegacy.f32(i32 59, %dx.types.Handle {handle}, i32 15)
  %hgSecondR = extractvalue %dx.types.CBufRet.f32 %hgSecond, 0
  %hgSecondG = extractvalue %dx.types.CBufRet.f32 %hgSecond, 1
  %hgSecondB = extractvalue %dx.types.CBufRet.f32 %hgSecond, 2
  %hgControlF = extractvalue %dx.types.CBufRet.f32 %hgSecond, 3
  %hgControl = fptoui float %hgControlF to i32
  %hgEnabled = icmp uge i32 %hgControl, 65536
  %hgPosU = and i32 %hgControl, 255
  %hgSmoothShift = lshr i32 %hgControl, 8
  %hgSmoothU = and i32 %hgSmoothShift, 255
  %hgPosF = uitofp i32 %hgPosU to float
  %hgSmoothF = uitofp i32 %hgSmoothU to float
  %hgPosition = fmul float %hgPosF, 0x3F70101020000000
  %hgWidth0 = fmul float %hgSmoothF, 0x3F70101020000000
  %hgWidth = call float @dx.op.binary.f32(i32 35, float %hgWidth0, float 0x3F50101020000000)
  %hgHalfWidth = fmul float %hgWidth, 5.000000e-01
  %hgStart = fsub float %hgPosition, %hgHalfWidth
  %hgShifted = fsub float %hgHeight, %hgStart
  %hgRamp0 = fdiv float %hgShifted, %hgWidth
  %hgRamp = call float @dx.op.unary.f32(i32 7, float %hgRamp0)
  %hgSquared = fmul float %hgRamp, %hgRamp
  %hgTwice = fmul float %hgRamp, 2.000000e+00
  %hgCurve = fsub float 3.000000e+00, %hgTwice
  %hgBlend0 = fmul float %hgSquared, %hgCurve
  %hgBlend = select i1 %hgEnabled, float %hgBlend0, float 0.000000e+00
'''
    for c,(first,second) in enumerate(zip(channels,('%hgSecondR','%hgSecondG','%hgSecondB'))):
        code+=f'  %hgDelta{c} = fsub float {second}, {first}\n  %hgPart{c} = fmul float %hgDelta{c}, %hgBlend\n  %hgColor{c} = fadd float {first}, %hgPart{c}\n'
    tail=text[at:]
    for c,old in enumerate(channels):tail=re.sub(re.escape(old)+r'(?!\d)',f'%hgColor{c}',tail)
    text=text[:at]+code+tail
    # Extend the reflected material CB type and resource size to include reg15.
    text=re.sub(r'(%cbMtdParam = type \{ .*?)( \}\n)',r'\1, [6 x float]\2',text,count=1)
    text=re.sub(r'(%cbMtdParam\* undef, !"", i32 0, i32 3, i32 1, )i32 \d+',r'\g<1>i32 256',text)
    return text

def mtd_rows(raw):
    offset=struct.unpack_from('<Q',raw,32)[0]
    count=struct.unpack_from('<I',raw,44)[0]
    rows=[]
    for i in range(count):
        at=offset+80*i
        name_at=struct.unpack_from('<Q',raw,at)[0]
        name=raw[name_at:].decode('utf-16-le',errors='replace').split('\0')[0]
        rows.append((name,raw[at:at+80]))
    return rows

def patch_metadata(raw,eye_raw):
    own=mtd_rows(raw)
    borrowed=[r for name,r in mtd_rows(eye_raw) if 'color' in name.lower()]
    assert len(borrowed)==1,[(n) for n,_ in mtd_rows(eye_raw)]
    name=next(n for n,r in mtd_rows(eye_raw) if r==borrowed[0])
    extra=bytearray(borrowed[0])
    result=bytearray(raw)
    if len(result)%2:result.append(0)
    struct.pack_into('<Q',extra,0,len(result))
    result+=name.encode('utf-16-le')+b'\0\0'
    struct.pack_into('<ii',extra,36,60,max(struct.unpack_from('<i',r,40)[0] for _,r in own)+1)
    struct.pack_into('<5f',extra,52,0,0,0,0,1)
    while len(result)%16:result.append(0)
    struct.pack_into('<Q',result,32,len(result))
    struct.pack_into('<I',result,44,len(own)+1)
    # The original allocation is already larger than the 256-byte CB.
    struct.pack_into('<I',result,52,max(256,struct.unpack_from('<I',raw,52)[0]))
    result+=b''.join(r for _,r in own)+extra
    checked=mtd_rows(result)
    assert checked[:-1]==own and checked[-1][0]==name
    return bytes(result)

def patch_bundle(bnd,eye):
    eye_meta=next(e.data for e in eye.entries if e.name.endswith('.metaparam'))
    counts={'vertex':0,'pixel':0,'metadata':0}
    for e in bnd.entries:
        if e.name.endswith('.metaparam'):
            e.data=patch_metadata(e.data,eye_meta);counts['metadata']+=1
        elif e.name.endswith(('.vpo','.ppo')):
            text=disassemble(e.data,e.name)
            modified=patch_vertex(text) if e.name.endswith('.vpo') else patch_pixel(text)
            if modified is None:continue
            (LAB/'dxil'/(e.name+'.gradient.ll')).write_text(modified,encoding='utf-8')
            try:e.data=assemble(modified)
            except Exception as error:raise RuntimeError(f'{e.name}: {error}') from error
            counts['vertex' if e.name.endswith('.vpo') else 'pixel']+=1
    assert counts['vertex'] and counts['pixel'] and counts['metadata']==1,counts
    return counts

